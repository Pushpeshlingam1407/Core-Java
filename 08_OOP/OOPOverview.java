
/*
 * ============================================================================
 *                    OBJECT-ORIENTED PROGRAMMING (OOP)
 * ============================================================================
 *
 *
 * //TODO: 1. OOP (OBJECT-ORIENTED PROGRAMMING): DEFINITION
 *
 * -- It is a programming paradigm that represents real-world scenarios
 *    in the Java programming perspective.
 *
 * -- Every real-world object can be recognized by using its features
 *    and behaviours/functions.
 *
 * -- They can be represented in Java by using variables and methods
 *    respectively.
 *
 * -- Phone has features/specifications/properties:
 *      1. brand
 *      2. model
 *      3. Camera
 *      4. battery
 *      5. Color
 *      6. Storage
 *      7. cost, etc.
 *
 * -- Phone has Functions/Behaviours/actions:
 *      1. Calling
 *      2. Chatting
 *      3. ClickPic
 *      4. Watching movies/Reels
 *      5. Playing games
 *
 * ----------------------------------------------------------------------------
 *
 *
 * //TODO: 2. CLASS: DEFINITION & DETAILS
 *
 * ----------------------------------------------------------------------------
 *
 * Class:
 *
 * -- It is a keyword which is used to create a user-defined reference datatype.
 *
 * -- It is used to define the blueprint of an object.
 *
 * ----------------------------------------------------------------------------
 *
 *
 * //TODO: 3. OBJECT: DEFINITION & DETAILS
 *
 * ----------------------------------------------------------------------------
 *
 * Object:
 *
 * -- It is defined as an instance of a class (blueprint class).
 *
 *
 * //TODO: NOTE:
 *
 * Note:
 *
 *      1. A class that defines the properties and behaviours of objects
 *         and is used to create objects is called a blueprint class
 *         or business logic class or logic entity class.
 *
 *      2. A class that contains the main() method and is used to create
 *         objects and execute the program is commonly called a
 *         user logic class or driver class.
 *
 *      3. In Java, an object is a real-world entity represented in
 *         programming. It is an instance of a class, containing its own
 *         state (data) and providing behaviour (methods).
 *
 *
 * ============================================================================
 */