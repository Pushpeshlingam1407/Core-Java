import java.util.*;

public class Examples2 {

  public static void main(String[] args) {
    System.out.println(12 & 3);
    System.out.println(12 | 3);
    System.out.println(~3);
    System.out.println(12 ^ 3);
    System.out.println(-12 >> 3);
    System.out.println(-12 << 3);
    System.out.println(-112 >>> 3);
  }
}
