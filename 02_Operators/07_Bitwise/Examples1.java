//TODO: Evaluate bitwise operations (&, |, ^, >>, <<, >>>, ~) on positive integer operands

import java.util.*;

public class Examples1 {

  public static void main(String[] args) {
    System.out.println(10 & 3);
    System.out.println(10 | 3);
    System.out.println(10 ^ 3);
    System.out.println(10 >> 3);
    System.out.println(10 << 3);
    System.out.println(10 >>> 3);
    System.out.println(~12);
  }
}
